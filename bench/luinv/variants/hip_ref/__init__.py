from functools import cached_property
from pathlib import Path
import re

import numpy as np

from bench.luinv.rawhip import PTR, RawHIPModule, hipcc_compatible
from bench.luinv.variants.baseline import LUInverse as BaselineLUInverse


HERE = Path(__file__).parent
INCLUDE = HERE / 'include'
GENERATED = INCLUDE / 'luinv' / 'hip_ref' / 'generated'

# The frozen baseline template
TEMPLATE = 'bench.luinv.variants.baseline.lu_inv_baseline'


# Phases of the kernel, each starting at the given occurrences (all if
# None) of a comment of the template; the forward and backward solves
# reuse the staging of diagonal blocks from the TRSM of the factorisation
_STAGE = '// Stage the diagonal block of the factor into the padded array md'
_UPDATE = '// Subtract the product of the factor with the rows already solved'

PHASES = [
    ('setup', None, None),
    ('build', '// Materialise I - scale*src', None),
    ('panel_load', "// Load this lane's rows of the panel into registers",
     None),
    ('pivot', '// Find the pivot: largest magnitude in column j', None),
    ('eliminate', '// Record the pivot and stage the pivot and diagonal rows',
     None),
    ('panel_store', '// Write the factored panel back', None),
    ('laswp', "// Apply the panel's row interchanges to the remaining", None),
    ('trsm', _STAGE, {0}),
    ('schur', '// Apply the Schur update to the trailing matrix', None),
    ('rhs_init', '// Start from this chunk of the columns of the identity',
     None),
    ('fwd_update', '// Solve the lower triangle a run of block rows', None),
    ('fwd_update', _UPDATE, {0, 1}),
    ('fwd_diag', _STAGE, {1, 2}),
    ('bwd_update', '// Solve the upper triangle a run of block rows', None),
    ('bwd_update', _UPDATE, {2, 3}),
    ('bwd_diag', _STAGE, {3, 4}),
    ('writeout', '// Write this chunk of the inverse out in pivoted order',
     None),
]

# Distinct phase names in order of first appearance
PHASE_NAMES = list(dict.fromkeys(p for p, *_ in PHASES))

# Lane zero of each block accumulates wall clock ticks per phase in LDS,
# adding them to a global array when the kernel finishes
_PHASE_PRELUDE = f'''
#define LUINV_NPH {len(PHASE_NAMES)}

struct LuinvPhaseFlush
{{
    unsigned long long *out, *acc, *t;
    int *cur;

    __device__ ~LuinvPhaseFlush()
    {{
        if (threadIdx.x == 0)
        {{
            acc[*cur] += wall_clock64() - *t;
            for (int i = 0; i < LUINV_NPH; i++)
                atomicAdd(out + i, acc[i]);
        }}
    }}
}};

#define LUINV_PHASE(k) do {{ if (threadIdx.x == 0) {{ \\
    unsigned long long _pt = wall_clock64(); \\
    luinv_phase_acc[luinv_phase_cur] += _pt - luinv_phase_t; \\
    luinv_phase_t = _pt; luinv_phase_cur = (k); }} }} while (0)
'''

_PHASE_INIT = '''__shared__ unsigned long long luinv_phase_acc[LUINV_NPH];
unsigned long long luinv_phase_t = wall_clock64();
int luinv_phase_cur = 0;
if (threadIdx.x == 0)
    for (int i = 0; i < LUINV_NPH; i++)
        luinv_phase_acc[i] = 0;
LuinvPhaseFlush luinv_phase_flush{luinv_phase_out, luinv_phase_acc,
                                  &luinv_phase_t, &luinv_phase_cur};
'''


def header_name(tplargs, phases=False):
    sfx = '_phases' if phases else ''
    return 'lu_inv_n{n}_{stype}_{ftype}_{otype}'.format(**tplargs) + \
        f'{sfx}.hpp'


def instrument(src):
    """Time the phases of the kernel, which gains a final argument."""
    src = re.sub(r'(void lu_inv_hip_ref\(.*)\)$',
                 r'\1, unsigned long long* __restrict__ luinv_phase_out)',
                 src, count=1, flags=re.M)

    # Start timing at the first statement of the body
    first = '// Offsets of the workspace and row order of the item'
    src = src.replace(first, _PHASE_INIT + first, 1)

    # Mark the start of each phase before its comment
    seen, lines = {}, []
    for l in src.splitlines():
        for name, marker, occs in PHASES:
            if marker and l.strip().startswith(marker):
                i = seen[name, marker] = seen.get((name, marker), -1) + 1
                if occs is None or i in occs:
                    indent = l[:len(l) - len(l.lstrip())]
                    k = PHASE_NAMES.index(name)
                    lines.append(f'{indent}LUINV_PHASE({k});')

        lines.append(l)

    return _PHASE_PRELUDE + '\n'.join(lines) + '\n'


def generate(backend, tplargs, phases=False):
    """Render the baseline kernel for the HIP route as a header."""
    src, *_ = backend.pointwise._render_kernel(
        'lu_inv_baseline', TEMPLATE, {}, tplargs, {}
    )

    src = hipcc_compatible(src)
    src = src.replace('void lu_inv_baseline(', 'void lu_inv_hip_ref(')
    if phases:
        src = instrument(src)

    hdr = ('// Generated by bench/luinv/variants/hip_ref from the frozen '
           'baseline\n// template; do not edit\n#pragma once\n' + src)

    path = GENERATED / header_name(tplargs, phases)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != hdr:
        path.write_text(hdr)

    return path


class LUInverse(BaselineLUInverse):
    @cached_property
    def module(self):
        hdr = generate(self.backend, self.tplargs)
        return RawHIPModule(self.backend, HERE / 'lu_inv.hip', INCLUDE,
                            defines={'LUINV_HEADER': hdr.name})

    @cached_property
    def kerns(self):
        b = self.backend
        argt = [b.ixdtype, b.fpdtype, PTR, PTR, PTR, PTR, b.ixdtype, PTR,
                PTR]
        block = (self.tplargs['nthreads'], 1, 1)

        # One kernel for each number of items inverted at once
        sizes = {v.n for ps in self.parts.values() for _, v in ps}
        return {s: self.module.kernel('lu_inv_hip_ref', argt, (s, 1, 1),
                                      block)
                for s in sizes}

    def invert(self, key, scale):
        for src, inv in self.parts[key]:
            kern = self.kerns[inv.n]
            kern.set_args(inv.n, scale, *inv.kargs('v'), self.perm,
                          *src.kargs('ml'), self.wk, self.ws)
            self.backend.run_kernels([kern])



class PhasedLUInverse(LUInverse):
    """The hip_ref kernel with the time spent in each phase recorded."""

    @cached_property
    def module(self):
        hdr = generate(self.backend, self.tplargs, phases=True)
        return RawHIPModule(self.backend, HERE / 'lu_inv.hip', INCLUDE,
                            defines={'LUINV_HEADER': hdr.name})

    @cached_property
    def phase_buf(self):
        return self.backend.hip.mem_alloc(8*len(PHASE_NAMES))

    def reset_phases(self):
        self.backend.wait()
        self.backend.hip.memset(self.phase_buf, 0, 8*len(PHASE_NAMES))

    def read_phases(self):
        self.backend.wait()

        out = np.zeros(len(PHASE_NAMES), dtype=np.uint64)
        self.backend.hip.memcpy(out, self.phase_buf, out.nbytes)

        # Wall clock ticks at 100 MHz summed over the blocks
        return {name: 1e-8*float(t) for name, t in zip(PHASE_NAMES, out)}

    @cached_property
    def kerns(self):
        b = self.backend
        argt = [b.ixdtype, b.fpdtype, PTR, PTR, PTR, PTR, b.ixdtype, PTR,
                PTR, PTR]
        block = (self.tplargs['nthreads'], 1, 1)

        sizes = {v.n for ps in self.parts.values() for _, v in ps}
        return {s: self.module.kernel('lu_inv_hip_ref', argt, (s, 1, 1),
                                      block)
                for s in sizes}

    def invert(self, key, scale):
        for src, inv in self.parts[key]:
            kern = self.kerns[inv.n]
            kern.set_args(inv.n, scale, *inv.kargs('v'), self.perm,
                          *src.kargs('ml'), self.wk, self.ws, self.phase_buf)
            self.backend.run_kernels([kern])
